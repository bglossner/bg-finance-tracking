import { readFileSync, writeFileSync } from 'node:fs';

const directory = new URL('./', import.meta.url);
const read = path => readFileSync(new URL(path, directory), 'utf8');
const core = read('core.js').trimEnd();
const check = process.argv.includes('--check');
const builds = [
  ['chase', 'chase-qfx-download.user.js'],
];

for (const [bank, filename] of builds) {
  const source = read(`adapters/${bank}.js`);
  const [, metadata, adapter] = /^(\/\/ ==UserScript==\n[^]*?\/\/ ==\/UserScript==)\n\n([^]+)$/.exec(source) ?? [];
  if (!metadata) throw new Error(`Missing userscript metadata in adapters/${bank}.js`);
  const result = `${metadata}\n\n// Generated by npm run build:userscripts from core.js and adapters/${bank}.js.\n\n(() => {\n${core}\n\n${adapter.trimEnd()}\n})();\n`;

  if (check) {
    if (result !== read(filename)) {
      console.error(`${filename} is stale. Run npm run build:userscripts.`);
      process.exitCode = 1;
    }
  } else {
    writeFileSync(new URL(filename, directory), result);
  }
}
